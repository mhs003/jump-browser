#!/usr/bin/env python3
"""Shrink an APK by recompressing its deflated entries with zopfli.

AGP deflates classes.dex and friends with zlib level 9. zopfli finds a
shorter DEFLATE stream for identical bytes, so the APK installs and runs
exactly the same but is a few percent smaller — measured ~50 KB on this
app, which is nearly all of the dex.

Stored entries are left stored and re-aligned to 16 KB: resources.arsc
must stay uncompressed on API 30+, and native libraries must be page
aligned for 16 KB-page devices.

The output is unsigned: every existing signature is stripped (v1 files in
META-INF, and the v2/v3 signing block, which is not a zip record and so
simply does not survive the rewrite). Run apksigner on the result:

    python3 scripts/repack_apk.py in.apk out.apk
    apksigner sign --ks <keystore> ... --out signed.apk out.apk
"""
import argparse
import struct
import sys
import zipfile
import zlib

# The strictest alignment Android can require for a stored entry: 16 KiB
# covers 4 KiB pages (resources.arsc on API 30+) and 16 KiB pages (.so).
ALIGN = 16384

# Files that carry a v1 JAR signature. They are regenerated by apksigner.
STRIP = {"META-INF/MANIFEST.MF"}


def alignment_padding(pos: int, name_len: int, boundary: int) -> tuple[int, bytes]:
    """Extra-field contents that put this entry's data on a `boundary` multiple.

    A local header is 30 bytes, then the name, then the extra field; the
    data offset that follows must be congruent to zero. The extra record
    itself is at least 4 bytes (id + size), so a remainder smaller than
    that wraps to the next boundary instead.
    """
    wanted = (-(pos + 30 + name_len)) % boundary
    if wanted == 0:
        return 0, b""
    if wanted < 4:
        wanted += boundary
    # 0xD935 is the "Android alignment" marker zipalign itself uses.
    return wanted, struct.pack("<HH", 0xD935, wanted - 4) + b"\x00" * (wanted - 4)


def stored_boundary(name: str) -> int:
    """Page size a stored entry must sit on, or 0 when it may sit anywhere.

    Native libraries must be 16 KiB aligned so 16 KB-page devices can map
    them; resources.arsc must be 4-byte aligned on API 30+. Baseline
    profiles are read byte-wise and need no alignment, as AGP itself
    writes them.
    """
    if name.startswith("lib/") and name.endswith(".so"):
        return ALIGN
    if name == "resources.arsc":
        return 4
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("src", help="APK to read")
    parser.add_argument("dst", help="repacked (unsigned) APK to write")
    parser.add_argument(
        "--iterations", type=int, default=15,
        help="zopfli iterations; 5+ for large files, 15 is a good default",
    )
    args = parser.parse_args()

    try:
        import zopfli.zlib as zopfli
    except ImportError:
        print("error: the 'zopfli' module is required (pip install zopfli)", file=sys.stderr)
        return 2

    src = zipfile.ZipFile(args.src)
    entries = [i for i in src.infolist() if not i.is_dir()]

    central = []
    total_before = total_after = 0
    with open(args.dst, "wb") as out:
        for info in entries:
            name = info.filename.encode()
            if info.filename in STRIP:
                continue
            if info.filename.startswith("META-INF/") and info.filename.endswith(
                (".SF", ".RSA", ".DSA", ".EC")
            ):
                continue
            raw = src.read(info.filename)
            crc = zlib.crc32(raw) & 0xFFFFFFFF
            usize = len(raw)
            boundary = stored_boundary(info.filename)
            if info.compress_type == zipfile.ZIP_STORED:
                # Stored entries must keep the alignment Packaging
                # guarantees; everything else about them is a copy.
                extra_len, extra = alignment_padding(out.tell(), len(name), boundary) if boundary else (0, b"")
                method, csize, data = 0, usize, raw
            else:
                extra_len, extra = 0, b""
                method = 8
                wrapped = zopfli.compress(raw, numiterations=args.iterations)
                # zopfli emits zlib format: a 2-byte header and a 4-byte
                # Adler-32 trailer wrap the raw DEFLATE stream zip entries use.
                data = wrapped[2:-4]
                csize = len(data)
            total_before += info.compress_size
            total_after += csize
            offset = out.tell()
            out.write(
                struct.pack(
                    "<IHHHHHIIIHH",
                    0x04034B50,  # local file header
                    20,          # version needed
                    0,           # flags: sizes known, no data descriptor
                    method,
                    0, 0,        # DOS time/date, zeroed for reproducibility
                    crc, csize, usize,
                    len(name), extra_len,
                )
            )
            out.write(name)
            out.write(extra)
            out.write(data)
            central.append((name, method, crc, csize, usize, offset))

        cd_start = out.tell()
        for name, method, crc, csize, usize, offset in central:
            out.write(
                struct.pack(
                    "<IHHHHHHIIIHHHHHII",
                    0x02014B50,  # central directory entry
                    20, 20,      # version made by / needed
                    0, method,
                    0, 0,
                    crc, csize, usize,
                    len(name), 0, 0, 0, 0, 0,
                    offset,
                )
            )
            out.write(name)
        cd_size = out.tell() - cd_start
        out.write(
            struct.pack(
                "<IHHHHIIH",
                0x06054B50,  # end of central directory
                0, 0, len(central), len(central),
                cd_size, cd_start,
                0,
            )
        )

    print(
        f"repacked {len(central)} entries: deflated payload "
        f"{total_before} -> {total_after} bytes "
        f"({(total_before - total_after) / 1024:.0f} KiB saved)"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
