#!/usr/bin/env python3
"""Shrink an APK by recompressing its entries with zopfli.

AGP deflates classes.dex and friends with zlib level 9. zopfli finds a
shorter DEFLATE stream for identical bytes, so the APK installs and runs
exactly the same but is a few percent smaller.

The one exceptions are entries Android requires stored: resources.arsc
must be uncompressed and 4-byte aligned on every app targeting API 30+,
and the baseline profile under assets/dexopt/ is read by ART directly
from the APK — a compressed profile is silently ignored.

Native libraries are extracted at install time (extractNativeLibs=true),
so they carry no alignment constraint and are compressed like everything
else.

The output is unsigned: every existing signature is stripped (v1 files in
META-INF, and the v2/v3 signing block, which is not a zip record and so
simply does not survive the rewrite). Run apksigner on the result:

    python3 scripts/repack_apk.py in.apk out.apk
    apksigner sign --ks <keystore> ... --out signed.apk out.apk
"""
import argparse
import struct
import sys
import zipfile
import zlib

# ART reads the baseline profile straight out of the APK; a compressed
# profile is silently ignored. resources.arsc must stay stored and 4-byte
# aligned on any app targeting API 30+ (AGP produces it that way; apksigner
# preserves the alignment when it rebuilds the zip for a v1 signature).
KEEP_STORED = (
    "assets/dexopt/",
    "resources.arsc",
)

# Files that carry a v1 JAR signature. They are regenerated by apksigner.
STRIP = {"META-INF/MANIFEST.MF"}


def align_extra(pos: int, name_len: int) -> tuple[int, bytes]:
    """Extra field that places a stored entry's data on a 4-byte boundary.

    A local header is 30 bytes, then the name, then this extra field; the
    data offset that follows must be congruent to zero. An extra record is
    at least 4 bytes (id + size), so a remainder of 1-3 wraps to 5-7 with
    a padded record. resources.arsc is the one entry that needs this:
    apksigner's rewrite shifts everything by a small constant, and a
    non-multiple of 4 there would fail to install on API 30+ devices.
    """
    wanted = (-(pos + 30 + name_len)) % 4
    if wanted == 0:
        return 0, b""
    if wanted < 4:
        wanted += 4
    return wanted, struct.pack("<HH", 0xD935, wanted - 4) + b"\x00" * (wanted - 4)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("src", help="APK to read")
    parser.add_argument("dst", help="repacked (unsigned) APK to write")
    parser.add_argument(
        "--iterations", type=int, default=15,
        help="zopfli iterations; 5+ for large files, 15 is a good default",
    )
    args = parser.parse_args()

    try:
        import zopfli.zlib as zopfli
    except ImportError:
        print("error: the 'zopfli' module is required (pip install zopfli)", file=sys.stderr)
        return 2

    src = zipfile.ZipFile(args.src)
    entries = [i for i in src.infolist() if not i.is_dir()]

    central = []
    total_before = total_after = 0
    with open(args.dst, "wb") as out:
        for info in entries:
            name = info.filename.encode()
            if info.filename in STRIP:
                continue
            if info.filename.startswith("META-INF/") and info.filename.endswith(
                (".SF", ".RSA", ".DSA", ".EC")
            ):
                continue
            raw = src.read(info.filename)
            crc = zlib.crc32(raw) & 0xFFFFFFFF
            usize = len(raw)
            if info.compress_type == zipfile.ZIP_STORED and info.filename.startswith(KEEP_STORED):
                # Stored verbatim, but re-aligned: the recompressed entries
                # before it shift its position.
                extra_len, extra = align_extra(out.tell(), len(name))
                method, csize = 0, usize
                data = raw
            else:
                extra, method = b"", 8
                wrapped = zopfli.compress(raw, numiterations=args.iterations)
                # zopfli emits zlib format: a 2-byte header and a 4-byte
                # Adler-32 trailer wrap the raw DEFLATE stream zip entries use.
                data = wrapped[2:-4]
                csize = len(data)
            total_before += info.compress_size
            total_after += csize
            offset = out.tell()
            out.write(
                struct.pack(
                    "<IHHHHHIIIHH",
                    0x04034B50,  # local file header
                    20,          # version needed
                    0,           # flags: sizes known, no data descriptor
                    method,
                    0, 0,        # DOS time/date, zeroed for reproducibility
                    crc, csize, usize,
                    len(name), len(extra),
                )
            )
            out.write(name)
            out.write(extra)
            out.write(data)
            central.append((name, method, crc, csize, usize, offset))

        cd_start = out.tell()
        for name, method, crc, csize, usize, offset in central:
            out.write(
                struct.pack(
                    "<IHHHHHHIIIHHHHHII",
                    0x02014B50,  # central directory entry
                    20, 20,      # version made by / needed
                    0, method,
                    0, 0,
                    crc, csize, usize,
                    len(name), 0, 0, 0, 0, 0,
                    offset,
                )
            )
            out.write(name)
        cd_size = out.tell() - cd_start
        out.write(
            struct.pack(
                "<IHHHHIIH",
                0x06054B50,  # end of central directory
                0, 0, len(central), len(central),
                cd_size, cd_start,
                0,
            )
        )

    print(
        f"repacked {len(central)} entries: payload "
        f"{total_before} -> {total_after} bytes "
        f"({(total_before - total_after) / 1024:.0f} KiB saved)"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
